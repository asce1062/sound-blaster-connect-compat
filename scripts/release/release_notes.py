#!/usr/bin/env python3
"""Release notes and CHANGELOG.md from Conventional Commits.

    release_notes.py changelog [--version X.Y.Z] [-o CHANGELOG.md]
    release_notes.py notes --tag <tag> [--metadata <apk>.json] [-o notes.md]

changelog  every v* tag becomes a section, newest first. Commits after the
           newest tag form the section of --version (release preparation)
           or "Unreleased". CHANGELOG.md is this output and is not edited by
           hand; the release commit regenerates it.
notes      the commits since the tag before <tag> (up to <tag>, or HEAD when
           the tag does not exist yet), plus the artifact facts from the
           release metadata JSON.

Merge commits are left out. Commit types map to sections; a subject that is
not a Conventional Commit goes under "Other".
"""

import argparse
import json
import re
import subprocess
import sys

SECTIONS = [
    ("feat", "Features"),
    ("fix", "Fixes"),
    ("build", "Build"),
    ("ci", "Continuous integration"),
    ("test", "Tests"),
    ("docs", "Documentation"),
    ("refactor", "Refactoring"),
    ("chore", "Maintenance"),
]
SUBJECT = re.compile(r"^(?P<type>[a-z]+)(\((?P<scope>[^)]+)\))?(?P<breaking>!)?: (?P<text>.+)$")


def git(*args):
    return subprocess.run(["git", *args], check=True, capture_output=True, text=True).stdout


def tags():
    out = git("tag", "--list", "v*", "--sort=-creatordate", "--format=%(refname:short)")
    return [t for t in out.splitlines() if t]


def commits(rev_range):
    out = git("log", "--no-merges", "--format=%H%x1f%s%x1f%as", rev_range)
    for line in out.splitlines():
        sha, subject, date = line.split("\x1f")
        yield sha, subject, date


def render_section(rev_range):
    groups = {key: [] for key, _ in SECTIONS}
    other, breaking = [], []
    for sha, subject, _ in commits(rev_range):
        m = SUBJECT.match(subject)
        if not m:
            other.append(f"- {subject} ({sha[:7]})")
            continue
        scope = f"**{m['scope']}**: " if m["scope"] else ""
        item = f"- {scope}{m['text']} ({sha[:7]})"
        if m["breaking"]:
            breaking.append(item)
        (groups[m["type"]] if m["type"] in groups else other).append(item)
    lines = []
    if breaking:
        lines += ["### Breaking changes", "", *breaking, ""]
    for key, title in SECTIONS:
        if groups[key]:
            lines += [f"### {title}", "", *groups[key], ""]
    if other:
        lines += ["### Other", "", *other, ""]
    return lines


def tag_date(tag):
    return git("log", "-1", "--format=%as", tag).strip()


def changelog(version):
    lines = [
        "# Changelog",
        "",
        "Generated by `scripts/release/release_notes.py changelog` from the commit",
        "history; not edited by hand.",
        "",
    ]
    tag_list = tags()
    head_range = f"{tag_list[0]}..HEAD" if tag_list else "HEAD"
    pending = render_section(head_range)
    if pending:
        title = f"## {version} (unreleased)" if version else "## Unreleased"
        lines += [title, "", *pending]
    for i, tag in enumerate(tag_list):
        rng = f"{tag_list[i + 1]}..{tag}" if i + 1 < len(tag_list) else tag
        lines += [f"## {tag[1:]} ({tag_date(tag)})", "", *render_section(rng)]
    return "\n".join(lines).rstrip() + "\n"


def notes(tag, metadata):
    tag_list = tags()
    exists = tag in tag_list
    end = tag if exists else "HEAD"
    earlier = tag_list[tag_list.index(tag) + 1:] if exists else tag_list
    rng = f"{earlier[0]}..{end}" if earlier else end
    lines = [f"# SB Connect Compat {tag}", ""]
    if metadata:
        m = json.load(open(metadata, encoding="utf-8"))
        lines += [
            "Compatibility build of Sound Blaster Connect "
            f"{m['version_name'].split('-compat.')[0]} for current Android, installed next to the stock app as "
            f"`{m['package']}`.",
            "",
            "| | |",
            "|---|---|",
            f"| File | `{m['file']}` |",
            f"| SHA-256 | `{m['sha256']}` |",
            f"| Version | {m['version_name']} (versionCode {m['version_code']}) |",
            f"| Signing certificate SHA-256 | `{m['certificate_sha256']}` |",
            f"| Signing mode | {m['signing_mode']} |",
            f"| Source commit | `{m['source_commit']}` |",
            f"| Stock input SHA-256 | `{m['stock_input_sha256']}` |",
            "",
            "Verify the download before installing it; see docs/user/INSTALLATION.md.",
            "",
        ]
    lines += ["## Changes", "", *render_section(rng)]
    return "\n".join(lines).rstrip() + "\n"


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("changelog")
    c.add_argument("--version")
    c.add_argument("-o", "--output")
    n = sub.add_parser("notes")
    n.add_argument("--tag", required=True)
    n.add_argument("--metadata")
    n.add_argument("-o", "--output")
    args = ap.parse_args()
    text = changelog(args.version) if args.cmd == "changelog" else notes(args.tag, args.metadata)
    if args.output:
        with open(args.output, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
